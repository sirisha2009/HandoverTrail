"use client";
import Link from "next/link";
import { useEffect, useState } from "react";
import { useUser } from "../lib/useUser";
import AuthBar from "../AuthBar";
import { sources, mockClaims } from "../../data/sample";

function Highlight({ text, snippet }) {
  const k = snippet ? text.indexOf(snippet) : -1;
  if (k < 0) return <span>{text}</span>;
  return (<span>{text.slice(0, k)}<mark>{snippet}</mark>{text.slice(k + snippet.length)}</span>);
}

export default function Demo() {
  const [claims, setClaims] = useState(null);
  const [srcs, setSrcs] = useState(sources);
  const [custom, setCustom] = useState("");
  const [loading, setLoading] = useState(false);
  const [err, setErr] = useState("");
  const [meta, setMeta] = useState("");
  const [role, setRole] = useState(null);
  const [openId, setOpenId] = useState(null);
  const [editId, setEditId] = useState(null);
  const [draft, setDraft] = useState("");
  const [version, setVersion] = useState(0);
  const [acked, setAcked] = useState(false);
  const [shareUrl, setShareUrl] = useState("");
  const [shareErr, setShareErr] = useState("");
  const [link, setLink] = useState("");
  const { user, supabase } = useUser();
  const [hid, setHid] = useState(null);
  const [busy, setBusy] = useState(false);
  const [cloud, setCloud] = useState("");
  const [gaps, setGaps] = useState(null);
  const [answers, setAnswers] = useState({});
  const [gapBusy, setGapBusy] = useState(false);
  const [gapErr, setGapErr] = useState("");
  const [repo, setRepo] = useState("");
  const [ghBusy, setGhBusy] = useState(false);

  // Keep the guest session across a refresh.
  useEffect(() => {
    try {
      const s = JSON.parse(sessionStorage.getItem("ht-demo") || "null");
      if (s) { if (s.claims) setClaims(s.claims); if (s.srcs) setSrcs(s.srcs); setVersion(s.version || 0); setRole(s.role || null); setMeta(s.meta || ""); setHid(s.hid || null); }
    } catch (e) {}
  }, []);
  useEffect(() => {
    try { sessionStorage.setItem("ht-demo", JSON.stringify({ claims, srcs, version, role, meta, hid })); } catch (e) {}
  }, [claims, srcs, version, role, meta, hid]);

  async function audit(action, detail, hidOverride) {
    const id = hidOverride || hid;
    if (!user || !supabase || !id) return;
    const { error } = await supabase.from("audit_log").insert({ handover_id: id, actor_email: user.email, action, detail: detail || {} });
    if (error) setCloud("Could not write the audit log: " + error.message);
  }

  async function run(list, label) {
    setLoading(true); setErr("");
    try {
      const r = await fetch("/api/generate", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ sources: list }) });
      const d = await r.json();
      if (!r.ok || !d.claims) throw new Error(d.error || "Generation failed.");
      setSrcs(list); setClaims(d.claims.map((c) => ({ ...c, status: "pending" }))); setMeta("Generated by AI (" + d.model + "). Quotes were re-checked against the sources.");
      setHid(null); setCloud("");
      if (user && supabase) {
        const title = (label || (list.length > 1 ? "Sample project" : list[0].title)) + " - " + new Date().toLocaleDateString();
        const { data: h, error: he } = await supabase.from("handovers").insert({ title }).select().single();
        if (he) setCloud("Could not save to your account: " + he.message);
        else { setHid(h.id); setCloud("Saved to your account."); await audit("generated", { sources: list.length, model: d.model }, h.id); }
      }
    } catch (e) { setErr(e.message); }
    setLoading(false);
  }
  const offline = () => { setSrcs(sources); setClaims(mockClaims.map((c) => ({ ...c, status: "pending" }))); setMeta("Offline sample output. The AI was not used."); setErr(""); };
  async function importRepo() {
    if (loading || ghBusy) return; setGhBusy(true); setErr("");
    try {
      const r = await fetch("/api/github?repo=" + encodeURIComponent(repo.trim()));
      const d = await r.json();
      if (!r.ok || !d.sources) throw new Error(d.error || "Import failed.");
      await run(d.sources, "GitHub import of " + d.repo);
    } catch (e) { setErr(e.message); }
    setGhBusy(false);
  }
  async function findGaps() {
    if (gapBusy) return; setGapBusy(true); setGapErr("");
    try {
      const r = await fetch("/api/gaps", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ sources: srcs.map((s) => ({ id: s.id, title: s.title, text: s.text })), claims: claims.map((c) => ({ type: c.type, text: c.text, confidence: c.confidence, note: c.note || "" })) }) });
      const d = await r.json();
      if (!r.ok || !d.questions) throw new Error(d.error || "Could not look for gaps.");
      setGaps(d.questions); setAnswers({}); audit("gaps_found", { count: d.questions.length });
    } catch (e) { setGapErr(e.message); }
    setGapBusy(false);
  }
  function addAnswers() {
    const filled = (gaps || []).filter((q) => answers[q.id] && answers[q.id].trim().length > 3);
    if (!filled.length) return;
    const texts = filled.map((q) => answers[q.id].trim().slice(0, 500));
    const prev = srcs.find((s) => s.id === "leaver");
    const src = { id: "leaver", title: "Leaver's answers", confidential: false, text: [prev && prev.text, ...texts].filter(Boolean).join("\n") };
    const add = filled.map((q, i) => ({ id: "g" + claims.length + "-" + i, type: q.type, text: texts[i], sourceId: "leaver", snippet: texts[i], confidence: "first-hand", note: "Answer to: " + q.question, status: "pending" }));
    setSrcs([...srcs.filter((s) => s.id !== "leaver"), src]);
    setClaims([...claims, ...add]);
    setGaps(gaps.filter((q) => !filled.includes(q))); setAnswers({});
    audit("answers_added", { count: add.length });
  }
  async function share() {
    if (busy) return; setBusy(true);
    setShareUrl(""); setShareErr("");
    try {
      const list = claims.filter((c) => c.status === "approved" && !c.confidential).map((c) => ({ ...c, sourceTitle: srcOf(c.sourceId)?.title || "" }));
      const r = await fetch("/api/share", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ claims: list, version }) });
      const d = await r.json();
      if (!r.ok || !d.path) throw new Error(d.error || "Could not create the link.");
      setShareUrl(window.location.origin + d.path);
      audit("shared", { version });
    } catch (e) { setShareErr(e.message); }
    setBusy(false);
  }
  async function publish() {
    if (busy) return; setBusy(true);
    const n = version + 1; setVersion(n); setAcked(false);
    if (user && supabase && hid) {
      const { error } = await supabase.from("versions").insert({ handover_id: hid, version_no: n, claims });
      if (error) setCloud("Could not save the version: " + error.message);
      else { setCloud("Version " + n + " saved to your account."); await audit("published", { version: n, approved: claims.filter((c) => c.status === "approved").length }); }
    }
    setBusy(false);
  }
  const openLink = () => { const k = link.indexOf("/handover/"); if (k < 0) return; window.location.href = link.slice(k).trim(); };
  const reset = () => { setClaims(null); setVersion(0); setAcked(false); setOpenId(null); setMeta(""); setHid(null); setCloud(""); };
  const set = (id, patch) => {
    const c0 = claims.find((c) => c.id === id);
    if (c0 && patch.text && patch.text !== c0.text) audit("edited", { from: c0.text.slice(0, 80), to: patch.text.slice(0, 80) });
    if (patch.status) audit(patch.status, { claim: (patch.text || (c0 && c0.text) || "").slice(0, 80) });
    setClaims(claims.map((c) => (c.id === id ? { ...c, ...patch } : c)));
  };
  const pending = claims ? claims.filter((c) => c.status === "pending").length : 0;
  const visible = (c) => role === "lead" || !c.confidential;
  const srcOf = (id) => srcs.find((s) => s.id === id);
  const approved = claims ? claims.filter((c) => c.status === "approved" && visible(c)) : [];
  const types = ["Decision", "Owner", "Blocker", "Risk", "Next action", "Contact"];

  return (
    <main>
      <div className="top">
        <Link href="/"><strong>HandoverTrail</strong></Link>
        <AuthBar />
        {role && (
          <div className="row" style={{ margin: 0 }}>
            <span className="badge type">Viewing as: {role === "lead" ? "Project lead" : "Joiner"}</span>
            {role === "lead" && <button className="btn sm ghost" onClick={() => setRole(null)}>Switch role</button>}
          </div>
        )}
      </div>
      <div className="wrap">
        {!role && (
          <div>
            <h2 style={{ marginTop: 0 }}>Who is viewing?</h2>
            <p className="mute">Choose a role to continue. In a real deployment the role would come from the user's login and permissions. Your session is kept when you switch roles, so a lead can publish and then check the joiner's view.</p>
            <div className="row" style={{ alignItems: "stretch" }}>
              <div className="card" style={{ flex: "1 1 280px" }}>
                <strong>Project lead</strong>
                <p className="mute">Reconstructs the project, reviews and approves claims, and publishes the handover. Sees everything, including confidential items.</p>
                <button className="btn" onClick={() => setRole("lead")}>Continue as Project lead</button>
              </div>
              <div className="card" style={{ flex: "1 1 280px" }}>
                <strong>Joiner</strong>
                <p className="mute">Takes over the work. Sees only the approved handover. Confidential items stay hidden.</p>
                <button className="btn amb" onClick={() => setRole("joiner")}>Continue as Joiner</button>
              </div>
            </div>
          </div>
        )}
        {role === "lead" && !claims && (
          <div className="card">
            <h2 style={{ marginTop: 0 }}>Step 1. Connect sources</h2>
            <p className="mute">Sample project: 4 sources (notes, task board, private chat). Click below to reconstruct the project state.</p>
            {sources.filter(visible).map((s) => (<div key={s.id} className="card"><strong>{s.title}</strong> {s.confidential && <span className="badge conf">confidential</span>}<p className="mute">{s.text}</p></div>))}
            <button className="btn" disabled={loading} onClick={() => run(sources)}>{loading ? "Analysing sources..." : "Generate handover"}</button>
            <h2>Or use your own notes</h2>
            <p className="mute">Paste meeting notes, a task list or a chat export. Use synthetic or permissioned text only.</p>
            <textarea rows={6} value={custom} onChange={(e) => setCustom(e.target.value)} placeholder="Paste your project notes here..." />
            <div className="row"><button className="btn amb" disabled={loading || custom.trim().length < 40} onClick={() => run([{ id: "u1", title: "Pasted notes", confidential: false, text: custom }])}>{loading ? "Analysing..." : "Generate from my notes"}</button></div>
            <h2>Or import a GitHub repository</h2>
            <p className="mute">Public repositories only. Reads recent commits, issues and pull requests, and every claim cites its link. Do not import private or confidential repositories.</p>
            <div className="row">
              <input value={repo} onChange={(e) => setRepo(e.target.value)} placeholder="owner/name, e.g. sirisha2009/HandoverTrail" style={{ flex: "1 1 260px", background: "#05070b", color: "var(--ink)", border: "1px solid var(--line)", borderRadius: 8, padding: 10, font: "inherit" }} />
              <button className="btn amb" disabled={loading || ghBusy || repo.trim().length < 3} onClick={importRepo}>{ghBusy || loading ? "Importing..." : "Import and generate"}</button>
            </div>
            {err && <div className="card" style={{ marginTop: 12 }}><p className="mute" style={{ color: "var(--red)" }}>{err}</p><button className="btn sm ghost" onClick={offline}>Show the offline sample instead</button></div>}
          </div>
        )}
        {role === "lead" && claims && (
          <div className="two">
            <div>
              <h2 style={{ marginTop: 0 }}>Review claims</h2>
              <p className="mute">{meta}</p>
              {cloud && <p className="mute">{cloud}</p>}
              {!user && supabase && <p className="mute">Guest demo: sign in with Google to save this handover, its versions and the audit log.</p>}<p className="mute">{pending} pending. Click a claim to see its source. Approve, edit or reject each one.</p><button className="btn sm ghost" onClick={reset}>Start over</button>
              {claims.filter(visible).map((c) => (
                <div key={c.id} className="card" style={{ opacity: c.status === "rejected" ? 0.45 : 1 }}>
                  <span className="badge type">{c.type}</span>
                  <span className={"badge " + c.confidence} style={c.confidence === "first-hand" ? { background: "#16304a", color: "#8ec5ff" } : undefined}>{c.confidence}</span>
                  {c.confidential && <span className="badge conf">confidential</span>}
                  {c.status !== "pending" && <span className="badge type">{c.status}</span>}
                  {editId === c.id ? (
                    <div><textarea rows={3} value={draft} onChange={(e) => setDraft(e.target.value)} />
                      <div className="row"><button className="btn sm" onClick={() => { set(c.id, { text: draft, status: "approved", confidence: "verified" }); setEditId(null); }}>Save and approve</button>
                        <button className="btn sm ghost" onClick={() => setEditId(null)}>Cancel</button></div></div>
                  ) : (<p style={{ margin: "8px 0", cursor: "pointer" }} onClick={() => setOpenId(c.id)}>{c.text}</p>)}
                  {c.note && <p className="mute">Note: {c.note}</p>}
                  {editId !== c.id && (
                    <div className="row">
                      <button className="btn sm" onClick={() => set(c.id, { status: "approved" })}>Approve</button>
                      <button className="btn sm amb" onClick={() => { setEditId(c.id); setDraft(c.text); }}>Edit</button>
                      <button className="btn sm red" onClick={() => set(c.id, { status: "rejected" })}>Reject</button>
                      <button className="btn sm ghost" onClick={() => setOpenId(c.id)}>View source</button>
                    </div>)}
                </div>
              ))}
            </div>
            <div>
              <h2 style={{ marginTop: 0 }}>Evidence</h2>
              {(() => {
                const c = claims.find((x) => x.id === openId);
                if (!c) return <div className="card mute">Select a claim to see where it came from.</div>;
                const s = srcOf(c.sourceId);
                if (!s) return <div className="card"><strong>No source found.</strong><p className="mute">This claim is an unverified assumption. Do not treat it as fact.</p></div>;
                return <div className="card"><strong>{s.title}</strong><p><Highlight text={s.text} snippet={c.snippet} /></p></div>;
              })()}
              <h2>Gaps to ask the leaver</h2>
              <div className="card">
                <p className="mute">Find what is missing or unclear and capture the leaver's answers as first-hand claims.</p>
                <button className="btn amb" disabled={gapBusy} onClick={findGaps}>{gapBusy ? "Looking for gaps..." : gaps ? "Find gaps again" : "Find gaps"}</button>
                {gapErr && <p className="mute" style={{ color: "var(--red)" }}>{gapErr}</p>}
                {gaps && gaps.length === 0 && <p className="mute">No open gaps.</p>}
                {gaps && gaps.map((q) => (<div key={q.id} style={{ marginTop: 12 }}><strong>{q.question}</strong><p className="mute">{q.reason}</p><textarea rows={2} value={answers[q.id] || ""} onChange={(e) => setAnswers({ ...answers, [q.id]: e.target.value })} placeholder="Leaver's answer..." /></div>))}
                {gaps && gaps.length > 0 && <div className="row"><button className="btn" disabled={!Object.values(answers).some((a) => a && a.trim().length > 3)} onClick={addAnswers}>Add answers as claims</button></div>}
              </div>
              <h2>Handover</h2>
              <div className="card">
                <p className="mute">Publish when every claim is reviewed. Joiners will not see confidential items.</p>
                <button className="btn" disabled={pending > 0 || approved.length === 0 || busy} onClick={publish}>Publish handover v{version + 1}</button>
              </div>
            </div>
          </div>
        )}
        {role === "joiner" && (
          <div className="card">
            <h2 style={{ marginTop: 0 }}>Open your handover</h2>
            <p className="mute">Joiners receive a private link from the project lead. Paste it here. You only ever see the approved handover, never the review workspace or confidential items.</p>
            <textarea rows={3} value={link} onChange={(e) => setLink(e.target.value)} placeholder="Paste the handover link here..." />
            <div className="row"><button className="btn" disabled={!link.includes("/handover/")} onClick={openLink}>Open handover</button></div>
          </div>
        )}
        {role === "lead" && version > 0 && (
          <div className="card" style={{ marginTop: 20 }}>
            <h2 style={{ marginTop: 0 }}>Handover v{version} (Project lead preview)</h2>
            {types.map((t) => { const items = approved.filter((c) => c.type === t); return items.length ? (
              <div key={t}><strong>{t}s</strong><ul>{items.map((c) => <li key={c.id}>{c.text} {c.confidential && <span className="badge conf">confidential</span>}<span className="mute">[{srcOf(c.sourceId)?.title || "no source"}]</span></li>)}</ul></div>) : null; })}
            <p className="mute">Confidential items are visible to you but are removed from the link that goes to the joiner.</p>
            <button className="btn" disabled={busy} onClick={share}>Create share link for the joiner</button>
            {shareErr && <p className="mute" style={{ color: "var(--red)" }}>{shareErr}</p>}
            {shareUrl && (<div className="card" style={{ marginTop: 12 }}>
              <p className="mute">Joiner link (approved, non-confidential items only):</p>
              <textarea readOnly rows={3} value={shareUrl} onFocus={(e) => e.target.select()} />
              <div className="row"><a className="btn sm amb" href={shareUrl} target="_blank" rel="noreferrer">Open joiner view</a></div>
            </div>)}
          </div>
        )}
      </div>
    </main>
  );
}
